"""TFLite inference utilities.

Mirrors the interface of `keras_utils.load_models_from_config` so that
`orchestrator_global` and `predictor_utils` can switch backends transparently.

The `TFLitePredictor` wrapper exposes `.predict(X, verbose=0)` and
`.input_shape` — a drop-in for Keras models inside the existing pipeline.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, Optional

import numpy as np

try:
    import tensorflow as tf
    # Always use the Interpreter bundled with TensorFlow itself.
    # A separately-installed `tflite_runtime` package may be older and
    # fail on opcodes generated by a newer TFLiteConverter (e.g. FULLY_CONNECTED v12).
    from tensorflow.lite.python.interpreter import Interpreter as _TFLiteInterpreter
    _TF_AVAILABLE = True
except Exception:
    tf = None  # type: ignore
    _TFLiteInterpreter = None
    _TF_AVAILABLE = False


def _find_flex_delegate() -> Optional[str]:
    """Locate the Flex delegate shared library inside the TF package directory.

    The Flex delegate is required to run models that include TensorList ops
    (e.g. LSTM-based models).  TF 2.x ships the .so in the package directory
    but does not auto-register it — we must pass it explicitly to the
    Interpreter.
    """
    if tf is None:
        return None
    import pathlib
    tf_dir = pathlib.Path(tf.__file__).parent
    # Known candidate paths across OS / TF packaging variants
    candidates = [
        tf_dir / 'lite' / 'python' / 'interpreter_wrapper' / 'libtensorflowlite_flex_delegate.so',
        tf_dir / 'lite' / 'experimental' / 'microfrontend' / 'python' / 'ops' / '_audio_microfrontend_op.so',
        tf_dir / '_pywrap_tensorflow_internal.so',  # monolithic — flex is inlined
    ]
    # Broader search: any *flex_delegate* or *flex* .so in the TF tree
    for candidate in tf_dir.rglob('*flex_delegate*.so'):
        candidates.insert(0, candidate)
    for path in candidates:
        if path.exists():
            return str(path) if 'flex_delegate' in path.name else None
    return None


# ---------------------------------------------------------------------------
# Predictor wrapper
# ---------------------------------------------------------------------------

class TFLitePredictor:
    """Wraps a tf.lite.Interpreter to expose a Keras-compatible API.

    Attributes
    ----------
    input_shape : tuple
        Shape with batch dimension replaced by None, e.g. (None, 128, 173, 1).
        Same format as Keras model.input_shape so upstream code (feature
        extractor, orchestrator n_mels detection) works unchanged.
    """

    def __init__(self, interpreter):
        self._interp = interpreter
        self._interp.allocate_tensors()

        inp_details = self._interp.get_input_details()[0]
        out_details = self._interp.get_output_details()[0]
        self._inp_idx = inp_details['index']
        self._out_idx = out_details['index']

        # Cast shape to tuple and replace concrete batch dim with None
        raw_shape = tuple(int(d) for d in inp_details['shape'])
        self.input_shape = (None,) + raw_shape[1:]

    def predict(self, X: np.ndarray, verbose: int = 0) -> np.ndarray:
        """Run inference on a batched float32 array.

        Processes each sample individually (TFLite interpreter is single-sample
        by design) and stacks results to (batch, n_classes).
        """
        X = np.asarray(X, dtype=np.float32)
        results = []
        for i in range(X.shape[0]):
            sample = X[i : i + 1]
            self._interp.resize_tensor_input(self._inp_idx, sample.shape)
            self._interp.allocate_tensors()
            self._interp.set_tensor(self._inp_idx, sample)
            self._interp.invoke()
            out = self._interp.get_tensor(self._out_idx)
            results.append(out[0])
        return np.array(results, dtype=np.float32)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _tflite_filename_for(info: dict) -> str:
    """Derive .tflite filename from a model config entry.

    Checks `tflite_filename` key first; falls back to replacing the .keras
    extension in `filename` with .tflite.  Fully generic — no hardcoding.
    """
    tflite_fn = info.get('tflite_filename')
    if tflite_fn:
        return tflite_fn
    keras_fn = info.get('filename', 'model.keras')
    return Path(keras_fn).stem + '.tflite'


# ---------------------------------------------------------------------------
# Public loader
# ---------------------------------------------------------------------------

def load_tflite_models_from_config(
    config: Dict,
    logger=None,
    timeout: int = 30,  # kept for API compatibility, unused by TFLite
) -> Dict[str, Dict]:
    """Load TFLite models listed in `config['models']['available_models']`.

    Returns the same dict structure as `keras_utils.load_models_from_config`:

        {
            name: {
                'model':        TFLitePredictor,
                'threshold':    float,
                'input_shape':  tuple,
                'description':  str,
                'architecture': str | None,
            },
            ...
        }
    """
    if not _TF_AVAILABLE:
        raise RuntimeError(
            'TensorFlow (with TFLite support) is required. '
            'Install with: pip install tensorflow'
        )

    models_dir = Path(config['models']['directory'])
    enabled: list = config['detection']['enabled_models']
    available: dict = config['models']['available_models']

    # Load thresholds (same logic as keras_utils)
    thresholds: Dict[str, float] = {}
    try:
        thresh_file = config['detection'].get('thresholds_file')
        if thresh_file:
            with open(thresh_file, 'r') as f:
                data = json.load(f)
            for k, v in data.get('models', {}).items():
                thresholds[k] = v.get('threshold', 0.5)
    except Exception:
        pass

    loaded: Dict[str, Dict] = {}

    for name in enabled:
        if name not in available:
            msg = f'[tflite] Model {name} not declared in available_models'
            logger.warning(msg) if logger else print(msg)
            continue

        info = available[name]
        tflite_fn = _tflite_filename_for(info)
        path = models_dir / tflite_fn

        if not path.exists():
            msg = f'[tflite] TFLite file not found: {path}'
            logger.warning(msg) if logger else print(msg)
            continue

        try:
            interp = _TFLiteInterpreter(model_path=str(path))
            predictor = TFLitePredictor(interp)
        except Exception as e:
            msg = f'[tflite] Failed to load {name} from {path}: {e}'
            logger.error(msg) if logger else print(msg)
            continue

        calibrated_key = info.get('calibrated_key', name)
        loaded[name] = {
            'model':        predictor,
            'threshold':    thresholds.get(calibrated_key, 0.5),
            'description':  info.get('description', ''),
            'architecture': info.get('architecture'),
            'input_shape':  predictor.input_shape,
            'predict_fn':   None,  # parity with keras_utils entry
        }
        msg = f'[tflite] Loaded {name} ({tflite_fn}) input_shape={predictor.input_shape}'
        logger.info(msg) if logger else print(msg)

    return loaded


