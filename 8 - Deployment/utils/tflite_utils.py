# CLI smoke-test
# ---------------------------------------------------------------------------

if __name__ == '__main__':
    import argparse
    import time

    parser = argparse.ArgumentParser(description='TFLite loader smoke-test')
    parser.add_argument('--config', default='deployment_config.json')
    parser.add_argument('--runs', type=int, default=3)
    args = parser.parse_args()

    with open(args.config, 'r') as f:
        cfg = json.load(f)

    models = load_tflite_models_from_config(cfg)
    print('Loaded TFLite models:', list(models.keys()))

    for name, info in models.items():
        predictor = info['model']
        ish = info['input_shape']
        print(f'\nSmoke predict — {name}  input_shape={ish}')
        dims = [d if d is not None else 1 for d in ish]
        X = np.zeros([1] + list(dims[1:]), dtype=np.float32)
        for i in range(args.runs):
            t0 = time.time()
            try:
                out = predictor.predict(X, verbose=0)
                dt = (time.time() - t0) * 1000
                print(f'  run {i+1}/{args.runs}  {dt:.1f} ms  out_shape={out.shape}')
            except Exception as e:
                print(f'  run {i+1}/{args.runs}  FAILED: {e}')
